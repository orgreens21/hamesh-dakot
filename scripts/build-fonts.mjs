// Downloads the site's Google Fonts (Hebrew + Latin subsets only) into assets/fonts/
// and writes shared/fonts.css, so pages work offline and never call Google at runtime.
// Usage: node scripts/build-fonts.mjs
import { writeFile } from 'node:fs/promises';

const FAMILIES = 'family=Heebo:wght@400;500;700;800&family=Frank+Ruhl+Libre:wght@500;700;900&family=Secular+One&display=swap';
const KEEP = new Set(['hebrew', 'latin']);
// Google only serves woff2 to browsers it recognises.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const root = new URL('..', import.meta.url);
const css = await (await fetch('https://fonts.googleapis.com/css2?' + FAMILIES, { headers: { 'User-Agent': UA } })).text();

const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)];
const files = new Map();
const out = [];
for (const [, subset, block] of blocks) {
  if (!KEEP.has(subset)) continue;
  const family = /font-family:\s*'([^']+)'/.exec(block)[1];
  const url = /url\(([^)]+)\)/.exec(block)[1];
  const slug = family.toLowerCase().replace(/\s+/g, '-');
  let name = files.get(url);
  if (!name) {
    name = `${slug}-${subset}-${files.size}.woff2`;
    files.set(url, name);
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`${res.status} for ${url}`);
    await writeFile(new URL('assets/fonts/' + name, root), Buffer.from(await res.arrayBuffer()));
  }
  out.push(block.replace(/url\([^)]+\)/, `url(../assets/fonts/${name})`));
}
if (!out.length) throw new Error('No font faces found; did the Google Fonts response change?');

await writeFile(new URL('shared/fonts.css', root),
  '/* Generated by scripts/build-fonts.mjs. Fonts: Heebo, Frank Ruhl Libre, Secular One (SIL Open Font License 1.1). */\n' +
  out.join('\n') + '\n');
console.log(`${out.length} font faces, ${files.size} files`);
