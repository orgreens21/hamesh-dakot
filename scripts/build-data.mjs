// Builds games/nekuda/data.js from Wikidata (items that carry an Israeli CBS locality code).
// Usage: node scripts/build-data.mjs
import { writeFile } from 'node:fs/promises';

const QUERY = `SELECT ?item ?code ?he ?coord ?pop ?typeHe WHERE {
  ?item wdt:P3466 ?code; wdt:P625 ?coord.
  ?item rdfs:label ?he. FILTER(lang(?he)="he")
  OPTIONAL { ?item wdt:P1082 ?pop }
  OPTIONAL { ?item wdt:P31 ?type. ?type rdfs:label ?typeHe. FILTER(lang(?typeHe)="he") }
}`;

// Localities that no longer exist (evacuated or merged) are dropped.
const DISSOLVED_QUERY = `SELECT ?item WHERE { ?item wdt:P3466 ?code; wdt:P576 ?end. }`;

async function load(query) {
  const url = 'https://query.wikidata.org/sparql?query=' + encodeURIComponent(query);
  const res = await fetch(url, {
    headers: { Accept: 'application/sparql-results+json', 'User-Agent': 'locality-game-data-fetch/1.0' },
  });
  if (!res.ok) throw new Error('Wikidata returned ' + res.status);
  return res.json();
}

// Type codes: 0 city, 1 local council / town, 2 kibbutz, 3 moshav, 4 community, 5 other
const TYPE_RULES = [
  [2, /קיבוץ/],
  [3, /מושב/],
  [0, /^עיר$|^עיר גדולה|עירייה|רשות מקומית עירונית/],
  [1, /מועצה מקומית|עיירה/],
  [4, /יישוב קהילתי|כפר/],
];
const NOT_A_PLACE = /מועצה אזורית|חלוקה מנהלית|בסיס|מוסד|פנימייה|חורבות|שכונה|כפר נוער/;

const NOT_A_PLACE_NAME = /אזור ה?תעשייה|ארכיון|מכללה|מחנה |בסיס |מועצה אזורית|בית ה?ספר|בית חולים|המרכז |מרכז רפואי|נמל התעופה|ישיבת |כפר הנוער/;

const rows = (await load(QUERY)).results.bindings;
const dissolved = new Set((await load(DISSOLVED_QUERY)).results.bindings.map((r) => r.item.value));
const byItem = new Map();
for (const r of rows) {
  const id = r.item.value;
  if (dissolved.has(id)) continue;
  const m = /Point\(([-\d.]+) ([-\d.]+)\)/.exec(r.coord.value);
  if (!m) continue;
  let e = byItem.get(id);
  if (!e) byItem.set(id, (e = { name: r.he.value, lon: +m[1], lat: +m[2], pop: 0, types: new Set() }));
  if (r.pop) e.pop = Math.max(e.pop, Math.round(+r.pop.value));
  if (r.typeHe) e.types.add(r.typeHe.value);
}

const out = new Map();
for (const e of byItem.values()) {
  if (e.lat < 29.4 || e.lat > 33.4 || e.lon < 34.2 || e.lon > 35.95) continue;
  const types = [...e.types];
  const placeTypes = types.filter((t) => !NOT_A_PLACE.test(t));
  if (types.length && !placeTypes.length) continue;
  let type = 5;
  for (const [code, re] of TYPE_RULES) if (placeTypes.some((t) => re.test(t))) { type = code; break; }
  if (e.pop >= 20000 && type !== 0) type = 0;
  const name = e.name.replace(/\s*\(.*?\)\s*/g, ' ').replace(/[\u0591-\u05c7]/g, (c) => (c === '־' ? '-' : '')).replace(/\s+/g, ' ').trim();
  if (NOT_A_PLACE_NAME.test(name)) continue;
  if (!name || !/[א-ת]/.test(name)) continue;
  const prev = out.get(name);
  if (!prev || prev[3] < e.pop) out.set(name, [name, +e.lat.toFixed(4), +e.lon.toFixed(4), e.pop, type]);
}

const list = [...out.values()].sort((a, b) => a[0].localeCompare(b[0], 'he'));
const body =
  '// Generated by scripts/build-data.mjs from Wikidata (CC0). Do not edit by hand.\n' +
  '// [name, lat, lon, population, type]\n' +
  'export const LOCALITIES = [\n' + list.map((r) => JSON.stringify(r)).join(',\n') + '\n];\n';
await writeFile(new URL('../games/nekuda/data.js', import.meta.url), body);
const big = list.filter((r) => r[3] >= 5000).length;
console.log(`localities: ${list.length}, with population >= 5000: ${big}`);
const byType = {}; for (const r of list) byType[r[4]] = (byType[r[4]] || 0) + 1;
console.log('by type', byType, 'no population:', list.filter((r) => !r[3]).length);
